"""Build the local UI catalog and wire known UI literals. No external service.

Translations are maintained in ui-translations.tsv (Spanish|English|Portuguese|French).
Run without --wire to regenerate Kotlin after changing translations. --inventory reports
untranslated literal templates; --wire wraps newly translated direct UI literals only.
For conditional labels, option lists and validation messages, add tr(...) explicitly.
This avoids interpreting a persisted category name or logic key as display copy.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / 'app/src/main/java/com/usuario/finanzas/ui'
catalog = {}
for line in (ROOT/'tools/ui-translations.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'): continue
    fields = [part.replace('\\n', '\n') for part in line.split('|')]
    if len(fields) != 4: raise ValueError(f'Expected four languages: {line}')
    if fields[0] in catalog: raise ValueError(f'Duplicate translation: {fields[0]}')
    slots = set(re.findall(r'\{\d+\}', fields[0]))
    assert all(set(re.findall(r'\{\d+\}', t)) == slots for t in fields), fields
    catalog[fields[0]] = fields[1:]

def quoted(text):
    return json.dumps(text, ensure_ascii=False).replace('$', '\\$')

out = UI/'i18n/Traducciones.kt'
out.parent.mkdir(exist_ok=True)
rows = '\n'.join('    '+quoted(k)+' to listOf('+', '.join(quoted(t) for t in v)+'),' for k,v in catalog.items())
out.write_text('''package com.usuario.finanzas.ui.i18n

import java.util.Locale

// Generated by tools/localize_ui.py from tools/ui-translations.tsv.
// Only UI copy uses this catalog; merchant names, category names and notes stay unchanged.
private val traducciones: Map<String, List<String>> = mapOf(
'''+rows+'''
)

/** Locale is read on every call so an in-app language switch does not retain old labels. */
fun tr(texto: String, vararg argumentos: Any?): String {
    val idioma = when (Locale.getDefault().language) { "en" -> 0; "pt" -> 1; "fr" -> 2; else -> -1 }
    val clave = texto.trim()
    val traducido = if (idioma >= 0) traducciones[clave]?.get(idioma) else null
    val resultado = if (traducido == null) texto else
        texto.takeWhile { it.isWhitespace() } + traducido + texto.takeLastWhile { it.isWhitespace() }
    // A single replacement pass preserves placeholders present inside user-provided values.
    return if (argumentos.isEmpty()) resultado else Regex("\\\\{(\\\\d+)\\\\}").replace(resultado) { coincidencia ->
        argumentos.getOrNull(coincidencia.groupValues[1].toInt())?.toString() ?: coincidencia.value
    }
}
''', encoding='utf-8')

inventory = {}
def transform(source, path, wire=False):
    def skip_comment(i):
        if source.startswith('//',i):
            e=source.find('\n',i); return len(source) if e<0 else e
        if source.startswith('/*',i):
            depth=1; e=i+2
            while depth and e<len(source):
                if source.startswith('/*',e): depth+=1; e+=2
                elif source.startswith('*/',e): depth-=1; e+=2
                else: e+=1
            return e
        return i
    def string(i):
        if source.startswith('"""',i):
            end=source.find('"""',i+3)+3
            return end,source[i:end]
        j=i+1; raw=[]; key=[]; args=[]
        while j<len(source):
            c=source[j]
            if c=='\\':
                pair=source[j:j+2]; raw.append(pair)
                key.append({'n':'\n','t':'\t','r':'\r','"':'"','\\':'\\','$':'$'}.get(pair[1], pair)); j+=2
            elif c=='"':
                j+=1; break
            elif source.startswith('${',j):
                expr_end,expr=code(j+2, stop_brace=True)
                args.append(expr); key.append('{'+str(len(args)-1)+'}')
                raw.append('${'+expr+'}'); j=expr_end+1
            elif c=='$' and j+1<len(source) and re.match(r'[A-Za-z_]',source[j+1]):
                m=re.match(r'\$([A-Za-z_][A-Za-z_0-9]*)',source[j:]); expr=m.group(1)
                args.append(expr);key.append('{'+str(len(args)-1)+'}');raw.append(m.group(0));j+=len(m.group(0))
            else: raw.append(c);key.append(c);j+=1
        key=''.join(key)
        inventory.setdefault(key, set()).add(str(path.relative_to(UI)))
        # Never change machine values, comparison operands, when-branch keys, or
        # category-name lookups. Automatic wiring has an intentionally narrow
        # allowlist; ambiguous contexts must be wrapped explicitly by the author.
        prefix = source[max(0,i-160):i]
        suffix = source[j:j+32]
        comparison = re.search(r'(?:===?|!==?|\bin|!in)\s*$', prefix) or re.match(r'\s*(?:===?|!==?|->)', suffix)
        direct_ui = re.search(
            r'(?:\bText\(\s*(?:text\s*=\s*)?|\bcontentDescription\s*=\s*|'
            r'\.(?:setTitle|setSubtitle|setNegativeButtonText)\(\s*)$', prefix
        )
        safe_ui = direct_ui and not comparison and key.strip() != 'Otros'
        # Do not rewrap a key already passed to tr. Argument expressions are still processed.
        already = re.search(r'\btr\(\s*$', source[max(0,i-25):i])
        if wire and safe_ui and key.strip() in catalog and not already:
            return j,'tr('+quoted(key)+('' if not args else ', '+', '.join(args))+')'
        return j,'"'+''.join(raw)+'"'
    def code(i=0,stop_brace=False):
        pieces=[]; depth=0
        while i<len(source):
            end=skip_comment(i)
            if end!=i: pieces.append(source[i:end]);i=end;continue
            c=source[i]
            if c=='"':
                end,new=string(i);pieces.append(new);i=end;continue
            if c=="'":
                e=i+1
                while e<len(source):
                    if source[e]=='\\': e+=2
                    elif source[e]=="'": e+=1;break
                    else:e+=1
                pieces.append(source[i:e]);i=e;continue
            if stop_brace:
                if c=='{':depth+=1
                elif c=='}':
                    if depth==0:return i,''.join(pieces)
                    depth-=1
            pieces.append(c);i+=1
        return i,''.join(pieces)
    return code()[1]

for path in sorted(UI.rglob('*.kt')):
    if 'i18n' in path.parts or path.name in ('Formato.kt',):continue
    source=path.read_text(encoding='utf-8')
    updated=transform(source,path,wire='--wire' in sys.argv)
    if updated!=source and '--wire' in sys.argv:
        if 'import com.usuario.finanzas.ui.i18n.tr' not in updated:
            updated=updated.replace('\n', '\n\nimport com.usuario.finanzas.ui.i18n.tr\n',1)
        path.write_text(updated,encoding='utf-8')
missing={k:sorted(v) for k,v in sorted(inventory.items()) if k.strip() not in catalog and re.search('[A-Za-zÀ-ÿ]{3}',k)}
(ROOT/'tools/ui-untranslated.json').write_text(json.dumps(missing,ensure_ascii=False,indent=2),encoding='utf-8')
print(f'{len(catalog)} translated keys; {len(missing)} uncatalogued strings (includes code/data values).')
